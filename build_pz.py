# Helper: set paragraph indent (first line ~12.5mm)
def indent_para(para):
    para.paragraph_format.first_line_indent = Cm(1.25)

# Helper: add normal paragraph with indent (JUSTIFIED)
def add_para(text, indent=True):
    p = doc.add_paragraph(text)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent:
        indent_para(p)
    return p

# Helper: add centered paragraph
def add_centered(text, size=14):
    p = doc.add_paragraph(text)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    for run in p.runs:
        run.font.name = 'Times New Roman'
        run.font.size = Pt(size)
        run.font.bold = False
        run.font.italic = False
    return p

# Helper: add heading with proper spacing
def add_heading(text, level=1):
    style_name = f'Heading {level}'
    # Configure the Heading style on first use
    try:
        hs = doc.styles[style_name]
    except KeyError:
        hs = doc.styles.add_style(style_name, WD_STYLE_TYPE.PARAGRAPH)
    hs.font.name = 'Times New Roman'
    hs.font.size = Pt(14)
    hs.font.bold = False
    hs.font.italic = False
    hs.font.color.rgb = RGBColor(0, 0, 0)
    hs.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    hs.paragraph_format.first_line_indent = Pt(0)
    hs.paragraph_format.line_spacing = 1.5
    space_map = {1: 24, 2: 18, 3: 12}
    hs.paragraph_format.space_before = Pt(space_map.get(level, 12))
    hs.paragraph_format.space_after = Pt(6)
    hs.paragraph_format.keep_with_next = True
    h = doc.add_paragraph(text, style=style_name)
    return h

# Helper: add right-aligned
