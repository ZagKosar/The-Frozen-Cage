# Helper: add formula line (text centered, number right-aligned)
def add_formula(formula_text, number):
    """Add a formula with text centered and formula number right-aligned"""
    para = doc.add_paragraph()
    para.paragraph_format.first_line_indent = Pt(0)
    # Add tab stops: center at mid-page, right at right margin
    # Page width: 210mm - 30mm - 10mm = 170mm
    para.paragraph_format.tab_stops.add_tab_stop(Cm(8.5), WD_ALIGN_PARAGRAPH.CENTER)
    para.paragraph_format.tab_stops.add_tab_stop(Cm(17), WD_ALIGN_PARAGRAPH.RIGHT)
    run = para.add_run(f"\t{formula_text}\t({number})")
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    run.font.bold = False
    run.font.italic = False
    return para

# Helper: add table
def add_table(headers, rows, title, caption=None):
    """Add table with formatting. headers = list of strings, rows = list of lists"""
    # Table title
    p = doc.add_paragraph(f"Таблица 1 – {title}")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    p.runs[0].font.name = 'Times New Roman'
    p.runs[0].font.size = Pt(12) if caption else Pt(14)
    
    cols = len(headers) if headers else len(rows[0])
    table = doc.add_table(rows=1 + len(rows), cols=cols)
    table.alignment = WD_ALIGN_PARAGRAPH.CENTER
    table.style = 'Table Grid'
    
    # Header row
    for j, h in enumerate(headers):
        cell = table.cell(0, j)
        cell.text = ''
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(12)
    
    # Data rows
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = table.cell(i + 1, j)
            cell.text = ''
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(str(val))
            run.font.name = 'Times New Roman'
            run.font.size = Pt(12)
    
    return table

